def audit_dataset() -> Dict[str, Any]:
    """Section 1: Dataset audit."""
    raw_df = load_dataset(config.RAW_DATASET_PATH)
    clean_df = clean_dataset(raw_df)

    summary = validate_dataset_summary(clean_df)
    total = len(clean_df)
    phish = int((clean_df["label"] == 1).sum())
    legit = int((clean_df["label"] == 0).sum())

    # Missing values
    missing = clean_df.isnull().sum().to_dict()

    # Duplicates
    dup_rows = int(clean_df.duplicated().sum())
    dup_urls = int(clean_df["url"].duplicated().sum())

    # Invalid URLs (empty after normalize)
    raw_normalized = raw_df.copy()
    raw_normalized["url_norm"] = raw_df["url"].apply(normalize_url)
    invalid_urls = int((raw_normalized["url_norm"] == "").sum())

    # Raw vs clean duplicate removal
    raw_dup_urls = int(raw_df["url"].duplicated().sum()) if "url" in raw_df.columns else 0

    # Suspicious/leakage-prone columns
    columns = list(clean_df.columns)
    leakage_risk = []
    if len(columns) > 2:
        leakage_risk.append("Extra columns beyond url/label may leak label information")
    # Check if label is derivable from URL patterns in synthetic data
    phishing_keywords_in_url = clean_df["url"].str.contains(
        r"attacker-|login-\d+|security-update|account-security-alert|\.tk|\.ml|\.ga|\.cf|\.gq|\.xyz",
        case=False, regex=True, na=False
    )
    keyword_label_corr = clean_df.groupby(phishing_keywords_in_url)["label"].mean().to_dict()

    audit = {
        "dataset_name": config.RAW_DATASET_NAME,
        "dataset_source": "Synthetic benchmark dataset generated by scripts/generate_dataset.py "
                          "(random.seed=42). Not sourced from external phishing feeds.",
        "raw_total_samples": len(raw_df),
        "clean_total_samples": total,
        "phishing_samples": phish,
        "legitimate_samples": legit,
        "phishing_pct": round(phish / total * 100, 2),
        "legitimate_pct": round(legit / total * 100, 2),
        "num_features": len(FEATURE_NAMES),
        "feature_names": FEATURE_NAMES,
        "missing_values": missing,
        "duplicate_rows": dup_rows,
        "duplicate_urls": dup_urls,
        "raw_duplicate_urls_before_cleaning": raw_dup_urls,
        "invalid_urls_removed": invalid_urls,
        "columns": columns,
        "leakage_risk_notes": leakage_risk,
        "url_pattern_label_correlation": keyword_label_corr,
        "rows_removed_in_cleaning": len(raw_df) - total,
    }
    return audit, clean_df


def check_train_test_leakage(clean_df: pd.DataFrame) -> Dict[str, Any]:
    """Check identical/near-identical URL overlap between train and test."""
    train_df, test_df = split_dataset(clean_df, test_size=config.TEST_SIZE, random_state=RANDOM_STATE)

    train_urls = set(train_df["url"].tolist())
    test_urls = set(test_df["url"].tolist())
    overlap = train_urls & test_urls

    # Near-identical: same hostname+path ignoring scheme
    def url_key(u):
        u = u.replace("https://", "").replace("http://", "")
        return u.lower().strip("/")

    train_keys = set(url_key(u) for u in train_urls)
    test_keys = set(url_key(u) for u in test_urls)
    near_overlap = train_keys & test_keys

    leakage = {
        "train_size": len(train_df),
        "test_size": len(test_df),
        "validation_size": 0,
        "split_ratio": f"{int((1 - config.TEST_SIZE) * 100)}/{int(config.TEST_SIZE * 100)}",
        "random_seed": RANDOM_STATE,
        "stratified": True,
        "cross_validation_in_production": False,
        "preprocessing_before_split": [
            "clean_dataset (dedup, normalize URLs, drop NA) applied BEFORE split — acceptable",
            "StandardScaler fit on TRAIN only — correct",
            "Feature extraction is per-URL, no global statistics — correct",
        ],
        "identical_url_overlap_count": len(overlap),
        "identical_url_overlap_examples": list(overlap)[:10],
        "near_identical_overlap_count": len(near_overlap),
        "data_leakage_detected": len(overlap) > 0,
        "critical_leakage": len(overlap) > 0,
    }
    return leakage, train_df, test_df


def prepare_features(train_df: pd.DataFrame, test_df: pd.DataFrame):
    X_train_raw = extract_features_df(train_df["url"].tolist())
    X_test_raw = extract_features_df(test_df["url"].tolist())
    y_train = train_df["label"].values
    y_test = test_df["label"].values

    scaler = StandardScaler()
    X_train = scaler.fit_transform(X_train_raw)
    X_test = scaler.transform(X_test_raw)
    return X_train, X_test, y_train, y_test, X_train_raw, X_test_raw, scaler


def compute_metrics(y_true, y_pred, y_proba=None) -> Dict[str, Any]:
    cm = confusion_matrix(y_true, y_pred)
    tn, fp, fn, tp = cm.ravel()
    metrics = {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "confusion_matrix": cm.tolist(),
        "tp": int(tp), "tn": int(tn), "fp": int(fp), "fn": int(fn),
        "phishing_recall": float(recall_score(y_true, y_pred, pos_label=1, zero_division=0)),
        "phishing_precision": float(precision_score(y_true, y_pred, pos_label=1, zero_division=0)),
        "false_negative_rate": float(fn / (fn + tp)) if (fn + tp) > 0 else 0.0,
        "false_positive_rate": float(fp / (fp + tn)) if (fp + tn) > 0 else 0.0,
    }
    if y_proba is not None:
        metrics["roc_auc"] = float(roc_auc_score(y_true, y_proba))
        metrics["pr_auc"] = float(average_precision_score(y_true, y_proba))
    return metrics


def train_and_evaluate_model(name, model, X_train, X_test, y_train, y_test):
    t0 = time.perf_counter()
    model.fit(X_train, y_train)
    train_time = time.perf_counter() - t0

    t1 = time.perf_counter()
    y_pred = model.predict(X_test)
    y_proba = model.predict_proba(X_test)[:, 1] if hasattr(model, "predict_proba") else None
    pred_time = (time.perf_counter() - t1) / len(y_test)

    metrics = compute_metrics(y_test, y_pred, y_proba)
    metrics["training_time_sec"] = round(train_time, 4)
    metrics["prediction_time_per_url_sec"] = round(pred_time, 6)
    metrics["model_name"] = name
    return metrics, model, y_pred, y_proba


def run_cross_validation(model_template, X, y, n_splits=5):
    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=RANDOM_STATE)
    scoring = ["accuracy", "precision", "recall", "f1", "roc_auc"]
    cv_results = cross_validate(model_template, X, y, cv=skf, scoring=scoring, n_jobs=-1)
    summary = {}
    for key in scoring:
        test_key = f"test_{key}"
        if test_key in cv_results:
            summary[f"mean_{key}"] = float(np.mean(cv_results[test_key]))
            summary[f"std_{key}"] = float(np.std(cv_results[test_key]))
    return summary


def threshold_analysis(model, scaler, test_df, y_test, thresholds=None):
    if thresholds is None:
        thresholds = [0.30, 0.40, 0.50, 0.60, 0.70]
    X_raw = extract_features_df(test_df["url"].tolist())
    X_scaled = scaler.transform(X_raw)
    y_proba = model.predict_proba(X_scaled)[:, 1]

    rows = []
    for t in thresholds:
        y_pred = (y_proba >= t).astype(int)
        m = compute_metrics(y_test, y_pred)
        rows.append({
            "threshold": t,
            "precision": m["precision"],
            "recall": m["recall"],
            "f1": m["f1"],
            "false_positives": m["fp"],
            "false_negatives": m["fn"],
        })
    return pd.DataFrame(rows)


def error_analysis(test_df, y_test, y_pred, y_proba, max_samples=5):
    df = test_df.copy()
    df["y_true"] = y_test
    df["y_pred"] = y_pred
    df["phishing_prob"] = y_proba

    fp = df[(df["y_true"] == 0) & (df["y_pred"] == 1)].head(max_samples)
    fn = df[(df["y_true"] == 1) & (df["y_pred"] == 0)].head(max_samples)
    tp = df[(df["y_true"] == 1) & (df["y_pred"] == 1)].head(max_samples)
    tn = df[(df["y_true"] == 0) & (df["y_pred"] == 0)].head(max_samples)

    def summarize(subset, label):
        if len(subset) == 0:
            return {"category": label, "count": 0, "samples": [], "common_traits": "None"}
        samples = []
        for _, row in subset.iterrows():
            feats = extract_features(row["url"])
            samples.append({
                "url": row["url"][:120],
                "phishing_prob": round(float(row["phishing_prob"]), 4),
                "has_ip": feats["has_ip"],
                "has_suspicious_keyword": feats["has_suspicious_keyword"],
                "count_at": feats["count_at"],
                "num_subdomains": feats["num_subdomains"],
            })
        traits = []
        if subset["url"].str.contains("@").any():
            traits.append("@ symbol")
        if subset["url"].str.contains(r"\d+\.\d+\.\d+\.\d+").any():
            traits.append("IP address")
        if subset["url"].str.contains(r"login-|security-update|\.tk|\.ml|\.ga").any():
            traits.append("synthetic phishing patterns")
        return {"category": label, "count": int(len(df[(df['y_true']==subset['y_true'].iloc[0]) & (df['y_pred']==subset['y_pred'].iloc[0])])), "samples": samples, "common_traits": ", ".join(traits) or "varied"}

    return {
        "false_positives": summarize(fp, "FP"),
        "false_negatives": summarize(fn, "FN"),
        "true_positives": summarize(tp, "TP"),
        "true_negatives": summarize(tn, "TN"),
    }


def robustness_testing(model, scaler):
    test_cases = [
        ("http://example.com/" + "a" * 500, "Very long URL"),
        ("https://a.b.c.d.e.f.example.com/path", "Many subdomains"),
        ("http://192.168.1.1/login", "IP address URL"),
        ("http://legitimate.com@evil.tk/login", "URL with @"),
        ("http://example.com/path?q=%E2%82%AC", "Unusual characters/encoding"),
        ("http://example.com/insecure", "HTTP URL"),
        ("https://example.com/secure", "HTTPS URL"),
        ("http://bit.ly/abc123", "URL shortening pattern"),
        ("http://xn--bcher-kva.example", "Punycode-like domain"),
        ("not_a_valid_url", "Malformed URL"),
        ("", "Empty URL"),
        ("<script>alert(1)</script>", "XSS payload"),
    ]
    results = []
    for url, desc in test_cases:
        status = "ok"
        prediction = None
        prob = None
        error = None
        try:
            if not url or not url.strip():
                status = "handled_empty"
            else:
                clean = normalize_url(url)
                feats = extract_features(clean)
                X = scaler.transform(pd.DataFrame([feats])[FEATURE_NAMES])
                pred = int(model.predict(X)[0])
                prob = float(model.predict_proba(X)[0][1])
                prediction = "Phishing" if pred == 1 else "Legitimate"
        except Exception as e:
            status = "error"
            error = str(e)
        results.append({
            "description": desc,
            "input_preview": url[:80] if url else "(empty)",
            "status": status,
            "prediction": prediction,
            "phishing_probability": prob,
            "error": error,
        })
    return results


def reproducibility_check(clean_df):
    results = []
    for run in [1, 2]:
        train_df, test_df = split_dataset(clean_df, test_size=config.TEST_SIZE, random_state=RANDOM_STATE)
        X_train, X_test, y_train, y_test, _, _, _ = prepare_features(train_df, test_df)
        rf = RandomForestClassifier(n_estimators=config.RF_N_ESTIMATORS, random_state=RANDOM_STATE, n_jobs=-1)
        rf.fit(X_train, y_train)
        m = compute_metrics(y_test, rf.predict(X_test), rf.predict_proba(X_test)[:, 1])
        m["run"] = run
        results.append(m)
    diff = {
        "accuracy_diff": abs(results[0]["accuracy"] - results[1]["accuracy"]),
        "f1_diff": abs(results[0]["f1"] - results[1]["f1"]),
        "identical": results[0]["accuracy"] == results[1]["accuracy"] and results[0]["f1"] == results[1]["f1"],
    }
    return results, diff


def feature_importance_analysis(rf_model, X_test, y_test):
    gini = sorted(zip(FEATURE_NAMES, rf_model.feature_importances_), key=lambda x: x[1], reverse=True)
    top10 = gini[:10]

    perm = permutation_importance(rf_model, X_test, y_test, n_repeats=10, random_state=RANDOM_STATE, n_jobs=-1)
    perm_sorted = sorted(zip(FEATURE_NAMES, perm.importances_mean), key=lambda x: x[1], reverse=True)[:10]

    return {"gini_top10": top10, "permutation_top10": perm_sorted}


def performance_metrics(rf_model, scaler):
    model_path = os.path.join(OUTPUT_DIR, "_temp_rf_eval.joblib")
    scaler_path = os.path.join(OUTPUT_DIR, "_temp_scaler_eval.joblib")
    joblib.dump(rf_model, model_path)
    joblib.dump(scaler, scaler_path)
    model_size = os.path.getsize(model_path)
    scaler_size = os.path.getsize(scaler_path)
    os.remove(model_path)
    os.remove(scaler_path)
    return {"model_file_size_bytes": model_size, "scaler_file_size_bytes": scaler_size}


def main():
    ensure_output_dir()
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    print("=== ML COMPREHENSIVE EVALUATION ===")
    print(f"Started: {timestamp}")

    # 1. Dataset audit
    audit, clean_df = audit_dataset()

    # 2. Train/test methodology & leakage
    leakage, train_df, test_df = check_train_test_leakage(clean_df)
    X_train, X_test, y_train, y_test, X_train_raw, X_test_raw, scaler = prepare_features(train_df, test_df)

    # 3-6. Model comparison
    models = {
        "Logistic Regression": LogisticRegression(max_iter=1000, random_state=RANDOM_STATE),
        "Decision Tree": DecisionTreeClassifier(random_state=RANDOM_STATE),
        "Random Forest": RandomForestClassifier(n_estimators=config.RF_N_ESTIMATORS, random_state=RANDOM_STATE, n_jobs=-1),
        "XGBoost": XGBClassifier(n_estimators=100, random_state=RANDOM_STATE, eval_metric="logloss", verbosity=0),
    }

    comparison = []
    all_predictions = {}
    rf_model = None
    rf_metrics = None
    rf_y_pred = None
    rf_y_proba = None

    for name, model in models.items():
        metrics, fitted, y_pred, y_proba = train_and_evaluate_model(name, model, X_train, X_test, y_train, y_test)
        comparison.append(metrics)
        all_predictions[name] = {"y_pred": y_pred, "y_proba": y_proba}
        if name == "Random Forest":
            rf_model = fitted
            rf_metrics = metrics
            rf_y_pred = y_pred
            rf_y_proba = y_proba

    comparison_df = pd.DataFrame([{
        "Model": m["model_name"],
        "Accuracy": round(m["accuracy"], 4),
        "Precision": round(m["precision"], 4),
        "Recall": round(m["recall"], 4),
        "F1": round(m["f1"], 4),
        "ROC AUC": round(m.get("roc_auc", 0), 4),
        "PR AUC": round(m.get("pr_auc", 0), 4),
        "Training Time (s)": m["training_time_sec"],
    } for m in comparison])
    comparison_df.to_csv(os.path.join(OUTPUT_DIR, "model_comparison.csv"), index=False)

    # Baseline = Logistic Regression
    baseline_metrics = comparison[0]

    # 5. Cross-validation (Random Forest)
    rf_cv_template = RandomForestClassifier(n_estimators=config.RF_N_ESTIMATORS, random_state=RANDOM_STATE, n_jobs=-1)
    X_full = np.vstack([X_train, X_test])
    y_full = np.concatenate([y_train, y_test])
    cv_summary = run_cross_validation(rf_cv_template, X_full, y_full)

    # 9. Feature importance
    feat_imp = feature_importance_analysis(rf_model, X_test, y_test)

    # 10. Threshold analysis
    threshold_df = threshold_analysis(rf_model, scaler, test_df, y_test)
    threshold_df.to_csv(os.path.join(OUTPUT_DIR, "threshold_analysis.csv"), index=False)

    # 11. Error analysis
    errors = error_analysis(test_df, y_test, rf_y_pred, rf_y_proba)

    # 12. Robustness
    robustness = robustness_testing(rf_model, scaler)
    pd.DataFrame(robustness).to_csv(os.path.join(OUTPUT_DIR, "robustness_tests.csv"), index=False)

    # 13. Reproducibility
    repro_runs, repro_diff = reproducibility_check(clean_df)

    # 14. Performance
    perf = performance_metrics(rf_model, scaler)

    # Also verify production train_model path
    prod_model, prod_scaler, prod_meta = train_model(df_clean=clean_df)
    prod_X_test = prod_meta["X_test_scaled"]
    prod_y_test = prod_meta["y_test"]
    prod_metrics = compute_metrics(prod_y_test, prod_model.predict(prod_X_test), prod_model.predict_proba(prod_X_test)[:, 1])

    # Save all JSON results
    results = {
        "timestamp": timestamp,
        "audit": audit,
        "leakage": leakage,
        "baseline": baseline_metrics,
        "random_forest": rf_metrics,
        "production_rf": prod_metrics,
        "comparison": comparison,
        "cross_validation": cv_summary,
        "feature_importance": {
            "gini_top10": feat_imp["gini_top10"],
            "permutation_top10": feat_imp["permutation_top10"],
        },
        "threshold_analysis": threshold_df.to_dict(orient="records"),
        "error_analysis": errors,
        "robustness": robustness,
        "reproducibility": {"runs": repro_runs, "diff": repro_diff},
        "performance": perf,
    }

    with open(os.path.join(OUTPUT_DIR, "evaluation_results.json"), "w") as f:
        json.dump(results, f, indent=2, default=str)

    print("\n=== SUMMARY ===")
    print(comparison_df.to_string(index=False))
    print(f"\nData leakage: {'YES' if leakage['data_leakage_detected'] else 'NO'}")
    print(f"Reproducible: {'YES' if repro_diff['identical'] else 'NO'}")
    print(f"\nResults saved to {OUTPUT_DIR}")
    return results


if __name__ == "__main__":
    main()
